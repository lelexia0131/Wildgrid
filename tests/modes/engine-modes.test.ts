import { test } from 'node:test';
import assert from 'node:assert/strict';
import { abandonSurvivalChallenge, createSurvivalSave, emptySurvivalProgress, replaceSurvivalChallenge, settleSurvival, updateSurvivalProgress } from '../../src/game-modes/survival/survivalChallenge';
import { adventureSaveWritable, createAdventureSave, parseAdventureSave } from '../../src/save-system/adventureSaveCodec';
import { completeAdventureLevel, levelUnlocked, progressForPlay, recordAdventureProgress } from '../../src/game-modes/adventure/adventureProgress';
import { getLevelById, getSolution, withEditorPlacements } from '../../src/engine';
import { parseLocalMapsForWrite, parseLocalMapsSave, serializeLocalMaps } from '../../src/save-system/localMapSaveCodec';
import { parseSurvivalForWrite, serializeSurvivalSave } from '../../src/save-system/survivalSaveCodec';
import { survivalCollectionTarget, upsertLocalMap } from '../../src/game-modes/sandbox/localMapCollection';
import type { SurvivalChallenge } from '../../src/game-modes/survival/survivalChallenge';

test('adventure engine preserves v1 progress and unlocks without platform storage', () => {
  const original = createAdventureSave(), level = getLevelById(1)!, solution = getSolution(1)!;
  const playing = recordAdventureProgress(original, 1, solution);
  const completed = completeAdventureLevel(playing, 15);
  assert.deepEqual(original.progress, {});
  assert.deepEqual(playing.completed, []);
  assert.equal(levelUnlocked(31, completed.completed), true);
  assert.deepEqual(progressForPlay(completed, level), []);
  const restored = parseAdventureSave(JSON.stringify(completed));
  assert.deepEqual(restored.progress[1], solution);
  assert.deepEqual(restored.completed, completed.completed);
  assert.deepEqual(restored.settings, completed.settings);
  assert.equal(adventureSaveWritable('{"version":2}'), false);
  assert.throws(() => parseAdventureSave('{broken'));
});

test('survival transitions and local blueprint access use explicit snapshots and preserve their inputs', () => {
  const level = { ...getLevelById(6)!, size: 8 }, placements = getSolution(6)!;
  const draft = withEditorPlacements({ level, placements }, placements);
  const first: SurvivalChallenge = { id: 'engine-first', difficulty: 1, seed: 1, startedAt: 10, draft, fingerprint: 'first' };
  const second = { ...first, id: 'engine-second', fingerprint: 'second' };
  const fresh = createSurvivalSave(), active = replaceSurvivalChallenge(fresh, first);
  const progress = { ...emptySurvivalProgress(first.id), placements: placements.slice(0, 1) };
  const playing = updateSurvivalProgress(active, first.id, progress);
  const target = survivalCollectionTarget([], playing, first);
  const collection = upsertLocalMap([], draft, [], target.existingId, target.survival);
  const storedMaps = serializeLocalMaps(collection.maps);
  assert.equal(parseLocalMapsSave(storedMaps, playing)[0].survival?.blueprintUnlocked, false);
  const replaced = replaceSurvivalChallenge(playing, second);
  assert.equal(fresh.challenge, null);
  assert.deepEqual(active.progress?.placements, []);
  assert.deepEqual(playing.records, []);
  assert.deepEqual(replaced.records[0].placements, placements.slice(0, 1));
  assert.equal(parseLocalMapsSave(storedMaps, replaced)[0].survival?.blueprintUnlocked, true);
  const abandoned = abandonSurvivalChallenge(playing, first.id);
  assert.equal(abandoned.challenge, null);
  assert.deepEqual(abandoned.completed, []);
  assert.equal(parseLocalMapsSave(storedMaps, abandoned)[0].survival?.completed, false);
  assert.throws(() => settleSurvival(abandoned, first, placements, 20), /挑战已结束/);
  const settled = settleSurvival(playing, first, placements, 20);
  assert.equal(settled.reward.earned, 1);
  assert.equal(settled.save.records[0].finishedAt, 20);
  assert.deepEqual(playing.completed, []);
  assert.equal(settleSurvival(settled.save, first, placements, 30).reward.earned, 0);
  assert.equal(parseLocalMapsSave(storedMaps, settled.save)[0].survival?.completed, true);
  assert.deepEqual(parseSurvivalForWrite(serializeSurvivalSave(settled.save)).completed, settled.save.completed);
  assert.throws(() => parseSurvivalForWrite('{"version":2}'), /原数据已保留/);
  assert.throws(() => parseLocalMapsForWrite('{broken', playing), /原数据已保留/);
});
